# Сан-маанилерди тексттерге бир жерден коёбуз.
_NUMS = {"pmin": PHOTO_MIN, "pmax": PHOTO_MAX, "days": AD_DAYS}
for _key in HELP:
    for _lg in HELP[_key]:
        if "%(" in HELP[_key][_lg]:
            HELP[_key][_lg] = HELP[_key][_lg] % _NUMS
del _key, _lg


def H(key, lang="ky"):
    """Жардам тексти — тандалган тилде. Табылбаса бош сап."""
    block = HELP.get(key)
    if not block:
        return ""
    return block.get("ru" if lang == "ru" else "ky", "")


def T(key, lang="ky"):
    """Сайттын жазуусу — тандалган тилде."""
