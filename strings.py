def L(text, lang="ky"):
    """
    «Кыргызча / Русский» түрүндөгү жазуудан керектүү жагын алат.

    Курама аталыш («A | B») ар бир бөлүгү өзүнчө тазаланат.
    """
    if not text:
        return ""
    out = []
    for part in str(text).split(" | "):
        halves = part.split(" / ")
        if len(halves) >= 2:
            out.append((halves[1] if lang == "ru" else halves[0]).strip())
        else:
            out.append(part.strip())
    return " | ".join(x for x in out if x)
