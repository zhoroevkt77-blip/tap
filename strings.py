# Сан-маанилерди тексттерге бир жерден коёбуз.
_NUMS = {"pmin": PHOTO_MIN, "pmax": PHOTO_MAX, "days": AD_DAYS}
for _key in HELP:
    for _lg in HELP[_key]:
        if "%(" in HELP[_key][_lg]:
            HELP[_key][_lg] = HELP[_key][_lg] % _NUMS
del _key, _lg


def H(key, lang="ky"):
    """Жардам тексти — тандалган тилде. Табылбаса бош сап."""
    block = HELP.get(key)
    if not block:
        return ""
    return block.get("ru" if lang == "ru" else "ky", "")


def T(key, lang="ky"):
    """Сайттын жазуусу — тандалган тилде."""
    pair = UI.get(key)
    if not pair:
        return key
    return pair[1] if lang == "ru" else pair[0]


def L(text, lang="ky"):
    """
    «Кыргызча / Русский» түрүндөгү жазуудан керектүү жагын алат.

    Курама аталыш («A | B») ар бир бөлүгү өзүнчө тазаланат.
    """
    if not text:
        return ""
    out = []
    for part in str(text).split(" | "):
        halves = part.split(" / ")
        if len(halves) >= 2:
            out.append((halves[1] if lang == "ru" else halves[0]).strip())
        else:
            out.append(part.strip())
    return " | ".join(x for x in out if x)
