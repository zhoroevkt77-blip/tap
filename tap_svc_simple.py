def apply(service_categories, service_group_tables):
    """Категорияларга жаңы subs коёт, топ таблицаларын өчүрөт."""
    ids = {c.get("id") for c in service_categories}
    missing = [k for k in SVC_SIMPLE if k not in ids]
    if missing:
        raise KeyError("SVC_SIMPLE: табылбаган категориялар: %s" % missing)
    for c in service_categories:
        new = SVC_SIMPLE.get(c.get("id"))
        if new is not None:
            c["subs"] = list(new) + [OTHER]
    for k in list(SVC_SIMPLE):
        service_group_tables.pop(k, None)
