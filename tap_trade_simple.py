def clothing_subs(demographic):
    d = DEMOGRAPHIC_ALIAS.get(demographic, demographic)
    return list(CLOTHING_SIMPLE.get(d) or CLOTHING_SIMPLE["men"]) + [OTHER]


def footwear_subs():
    return list(FOOTWEAR_SIMPLE) + [OTHER]


def apply(ns):
    """tap_catalog модулунун глобалдык аттарын (ns = globals()) жаңыртат."""
    cats = {c.get("id"): c for c in list(ns["TRADE_CATEGORIES"]) + list(ns["PROPERTY_CATEGORIES"])}
    missing = [k for k in TRADE_SIMPLE if k not in cats]
    if missing:
        raise KeyError("TRADE_SIMPLE: табылбаган категориялар: %s" % missing)
    for k, subs in TRADE_SIMPLE.items():
        cats[k]["subs"] = list(subs) + [OTHER]
        ns["GROUP_TABLES"].pop(k, None)
    ns["DEMOGRAPHICS"][:] = DEMOGRAPHICS_SIMPLE
    ns["get_clothing_subs"] = lambda demographic, season=None: clothing_subs(demographic)
    ns["get_footwear_subs"] = footwear_subs
