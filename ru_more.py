_KY = re.compile("[өүңӨҮҢ]")


def _geo():
    try:
        import tap_catalog as _c
        g = {}
        for nm in ("REGION_RU", "OBLAST_RU", "DISTRICT_RU"):
            g.update(getattr(_c, nm, {}) or {})
        return g
    except Exception:
        return {}


_GEO = None


def _name(x):
    return NAMES.get(x, x)


def _rx(s):
    """Калып боюнча которуу. Табылбаса None."""
    global _GEO
    if _GEO is None:
        _GEO = _geo()
    if s in _GEO:
        return _GEO[s]
    m = re.match(r"^(.+) облусу$", s)
    if m:
        return _name(m.group(1)) + " обл."
    m = re.match(r"^(.+) району$", s)
    if m:
        return _name(m.group(1)) + " район"
    m = re.match(r"^(.+) шаары$", s)
    if m:
        return "г. " + _name(m.group(1))
    m = re.match(r"^(.+) аэропорту$", s)
    if m:
        return "Аэропорт " + m.group(1)
    m = re.match(r"^Саат (.+?)(дө|до|да|де|тө|то|та|те) жолго чыгам$", s)
    if m:
        return "Выезжаю в " + m.group(1)
    m = re.match(r"^(\d{4})-ж\.?$", s)
    if m:
        return m.group(1) + " г."
    m = re.match(r"^(\d+)-кабат$", s)
    if m:
        return m.group(1) + " этаж"
    m = re.match(r"^(\d+)-(\w+)$", s)
    if m and m.group(2).lower() in _MONTHS:
        return m.group(1) + " " + _MONTHS[m.group(2).lower()]
    m = re.match(r"^([\d.,]+) тонна$", s)
    if m:
        return m.group(1) + " т"
    if s in NAMES:
        return NAMES[s]
    return None


def _one(s):
    """Бир бөлүктү которот (бөлбөй). Табылбаса None."""
    if not s:
        return None
    if s in RU:
        return RU[s]
    return _rx(s)


def _lead(s):
    i = 0
    while i < len(s) and (ord(s[i]) >= 0x2000 or s[i] in " \ufe0f"):
        i += 1
    return s[:i], s[i:]


def _bridge(s):
    try:
        import bridge
        r = bridge.ru_value(s, "ru")
        return r if r and r != s else None
    except Exception:
        return None


def tr(s):
    """
    Жалаң кыргызча сапты орусчага которот. Таба албаса None кайтарат
    (анда strings.L эски жол менен bridge'ге берет).
    """
    s = str(s or "").strip()
    if not s:
        return None
    if "\n" in s:
        ls = s.split("\n")
        rs = [tr(x) if x.strip() else x for x in ls]
        if any(r is not None for r in rs):
            return "\n".join(r if r is not None else x for r, x in zip(rs, ls))
        return None
    r = _one(s)
    if r is not None:
        return r
    hd, core = _lead(s)
    if hd and core:
        r = tr(core)
        if r is not None:
            return hd + r
        return None
    # «Ачкыч: маани»
    if ": " in s:
        k, v = s.split(": ", 1)
        rk = _one(k.strip())
        if rk is not None:
            rv = tr(v) or _bridge(v) or v
            return rk + ": " + rv
    # Курама: «А · Б», «А → Б», «А, Б»
    for sep in (" · ", " → ", " — ", ", "):
        if sep in s:
            parts = s.split(sep)
            out, hit = [], False
            for p in parts:
                q = tr(p) if sep != ", " else _one(p.strip())
                if q is None:
                    q = _bridge(p.strip())
                if q is not None:
                    hit = True
                    out.append(q)
                else:
                    out.append(p.strip())
            if hit:
                return sep.join(out)
    return None


_MISS = set()


def log_miss(text):
    """Орусча бетте кыргызча калса — логго бир жолу жазат."""
    try:
        if text and _KY.search(text) and text not in _MISS and len(_MISS) < 1000:
            _MISS.add(text)
            print("RUMISS:", text[:160], flush=True)
    except Exception:
        pass
