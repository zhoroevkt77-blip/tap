def _env_list(name):
    raw = os.environ.get(name) or ""
    return [x.strip().lower() for x in raw.split(",") if x.strip()]


HARD = HARD + _env_list("BAD_HARD")
SOFT = SOFT + _env_list("BAD_SOFT")
SWEAR = SWEAR + _env_list("BAD_SWEAR")
INSULT = INSULT + _env_list("BAD_INSULT")

# Латын тамгалары менен жашыруунун алдын алуу: a -> а, o -> о ж.б.
_LAT = "aAeEoOpPcCxXyYkKmMtTHB3"
_CYR = "аАеЕоОрРсСхХуУкКмМтТНВз"
_MAP = {ord(a): b for a, b in zip(_LAT, _CYR)}

_CLEAN = re.compile(r"[^0-9a-zа-яүөңі]+")
_REPEAT = re.compile(r"(.)\1{2,}")


def _norm(text):
    """Текстти салыштырууга даярдайт."""
    s = str(text or "").lower().replace("ё", "е")
    s = s.translate(_MAP).lower()
    s = _CLEAN.sub(" ", s)
    s = _REPEAT.sub(r"\1", s)
    return " " + " ".join(s.split()) + " "


def _hits(norm, words):
    """Сөздүн башы дал келсе табылды деп эсептейт (мис. наркотиктер)."""
    out = []
    for w in words:
        w = _norm(w).strip()
        if not w:
            continue
        if re.search(r"(?<![0-9a-zа-яүөңі])" + re.escape(w), norm):
            out.append(w)
    return out


def _squeezed(norm, words):
    """«н а р к о т и к» сыяктуу бөлүп жазууну кармайт."""
    flat = norm.replace(" ", "")
    out = []
    for w in words:
        w = _norm(w).strip()
        if len(w) >= 7 and " " not in w and w in flat:
            out.append(w)
    return out


def _exact(norm, words):
    """Толук сөз болуп келгенде гана табылды деп эсептейт."""
    return [w for w in (_norm(x).strip() for x in words)
            if w and (" " + w + " ") in norm]


def scan(*parts):
    """(деңгээл, сөздөр) кайтарат. Деңгээл: swear / hard / soft / "" """
    norm = _norm(" ".join(str(p or "") for p in parts))
    swear = (_hits(norm, SWEAR) or _exact(norm, SWEAR_EXACT)
             or _hits(norm, INSULT) or _exact(norm, INSULT_EXACT))
    if swear:
        return "swear", swear
    hard = _hits(norm, HARD) or _squeezed(norm, HARD)
    if hard:
        return "hard", hard
    soft = _hits(norm, SOFT) or _squeezed(norm, SOFT)
    if soft:
        return "soft", soft
    return "", []
